# overlay layers paint the robe, hat and hat rim: keep those texture areas free
RESERVED = [(16, 21, 30, 30), (0, 30, 30, 45), (0, 45, 52, 58)]


class Atlas:
    """Finds free texture space for extra boxes (box-UV footprint 2d+2w by d+h)."""

    def __init__(self, img):
        self.used = [[img.getpixel((x, y))[3] > 0 for x in range(64)] for y in range(64)]
        for x0, y0, x1, y1 in RESERVED:
            self.mark(x0, y0, x1 - x0, y1 - y0)

    def mark(self, x, y, w, h):
        for j in range(y, min(64, y + h)):
            for i in range(x, min(64, x + w)):
                self.used[j][i] = True

    def take(self, w, h, d):
        fw, fh = int(2 * d + 2 * w), int(d + h)
        for y in range(0, 64 - fh + 1):
            for x in range(32, 64 - fw + 1):
                if not any(self.used[j][i] for j in range(y, y + fh) for i in range(x, x + fw)):
                    self.mark(x, y, fw, fh)
                    return [x, y]
        raise RuntimeError("baby texture full")


def faces(uv, w, h, d):
    u, v = uv
    return {"top": (u + d, v, w, d), "bottom": (u + d + w, v, w, d), "right": (u, v + d, d, h),
            "front": (u + d, v + d, w, h), "left": (u + d + w, v + d, d, h), "back": (u + 2 * d + w, v + d, w, h)}


def paint(img, uv, size, fn):
    """fn(face, i, j, fw, fh) -> color or None, for every face of a box."""
    w, h, d = size
    px = img.load()
    for name, (x0, y0, fw, fh) in faces(uv, w, h, d).items():
        for j in range(int(fh)):
            for i in range(int(fw)):
                c = fn(name, i, j, int(fw), int(fh))
                if c:
                    px[x0 + i, y0 + j] = tuple(c[:3]) + (255,)


def part(model, name):
    return next(m for m in model["models"] if m["part"] == name)


def add_box(model, atlas, img, part_name, coords, fn, sub=None):
    """Add a box (top-level coords, or a submodel dict) and paint its UV."""
    w, h, d = coords[3:6]
    uv = atlas.take(w, h, d)
    box = B(coords, uv)
    if sub:
        sub = dict(sub, invertAxis="xy", boxes=[box])
        part(model, part_name).setdefault("submodels", []).append(sub)
    else:
        part(model, part_name)["boxes"].append(box)
    paint(img, uv, (w, h, d), fn)


