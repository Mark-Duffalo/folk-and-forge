# ---- vanilla baby geometry (jem frame: y up from the ground, x = entity's right) ------------
def P(part, t, boxes, **kw):
    return dict(part=part, id=part, invertAxis="xy", translate=t, boxes=boxes, **kw)


def B(c, uv, s=None):
    return dict(coordinates=c, textureOffset=uv, **({"sizeAdd": s} if s else {}))


