HEAD = {"top": (7, 0, 15, 7), "back": (22, 7, 30, 15), "right": (0, 7, 7, 15), "left": (15, 7, 22, 15), "front": (7, 7, 15, 15)}


def fill(img, rect, color):
    px = img.load()
    for y in range(rect[1], rect[3]):
        for x in range(rect[0], rect[2]):
            px[x, y] = color() if callable(color) else color + (255,)


def hair(img, pal, beard=False):
    """Hair on the baby head: top, back, upper sides, fringe and brows (rows/cols of the 8x8x7 head)."""
    import random
    rng = random.Random(len(pal))
    pick = lambda: pal[rng.choice([0, 0, 0, 1, 1, 2])] + (255,)
    fill(img, (7, 0, 15, 7), pick); fill(img, (22, 7, 30, 13), pick)
    fill(img, (0, 7, 7, 10), pick); fill(img, (0, 10, 3, 13), pick)           # right side: back half lower
    fill(img, (15, 7, 22, 10), pick); fill(img, (19, 10, 22, 13), pick)       # left side
    fill(img, (7, 7, 15, 8), pick); fill(img, (7, 8, 8, 10), pick); fill(img, (14, 8, 15, 10), pick)
    fill(img, (8, 11, 14, 12), pal[3] if len(pal) > 3 else pal[2])            # brows
    if beard:
        fill(img, (15, 0, 23, 7), pick)                                       # under the chin
        fill(img, (5, 12, 7, 15), pick); fill(img, (15, 12, 17, 15), pick)    # sideburns


def eyes(img, white, iris):
    px = img.load()
    for x in (8, 13):
        px[x, 12] = white + (255,)
    for x in (9, 12):
        px[x, 12] = iris + (255,)


def recolor_where(img, pred, fn):
    px = img.load()
    for y in range(64):
        for x in range(64):
            p = px[x, y]
            if p[3] and pred(x, y, p):
                px[x, y] = tuple(max(0, min(255, int(c))) for c in fn(p)) + (p[3],)


# ---- races ---------------------------------------------------------------------------------
HOBBIT_PAL = [(66, 46, 22), (87, 60, 29), (51, 36, 17), (40, 28, 12)]
DWARF_PAL = [(122, 66, 32), (138, 76, 37), (104, 55, 26), (88, 45, 20)]
SKINLIKE = lambda x, y, p: bv.is_skin(x, y, p) or tuple(p[:3]) in {(144, 94, 67), (119, 66, 53)}
NOT_EYE = lambda x, y, p: not (y == 12 and 8 <= x <= 13 and x not in (10, 11))


def baby_hobbit(img, model, atlas):
    hair(img, HOBBIT_PAL)


def baby_elf(img, model, atlas):
    ear = lambda f, i, j, fw, fh: None if (f in ("front", "back", "left", "right") and j == 0 and i != fw - 1) else (183, 130, 114)
    add_box(model, atlas, img, "head", [0, -1, -1, 1, 3, 2], ear,
            sub=dict(id="ear_r", translate=[4, 12, 0.5], rotate=[0, 0, -35]))
    add_box(model, atlas, img, "head", [-1, -1, -1, 1, 3, 2], ear,
            sub=dict(id="ear_l", translate=[-4, 12, 0.5], rotate=[0, 0, 35]))


def baby_dwarf(img, model, atlas):
    recolor_where(img, SKINLIKE, lambda p: (p[0], p[1] * 0.9, p[2] * 0.85))
    hair(img, DWARF_PAL, beard=True)
    art = ["LBBBBL", "BBLLBB", ".BGGB."]
    pal = {"B": DWARF_PAL[0], "L": DWARF_PAL[1], "D": DWARF_PAL[3], "G": (222, 172, 52)}
    def beard(f, i, j, fw, fh):
        if f == "front":
            return pal.get(art[j][i])
        if f in ("left", "right"):
            return pal["B"] if j < 2 else None
        return pal["B"] if f in ("top", "bottom") else None
    add_box(model, atlas, img, "head", [-3, 6, -4.4, 6, 3, 1], beard)


def copper_palette(jar):
    im = Image.open(io.BytesIO(jar.read("assets/minecraft/textures/block/copper_block.png"))).convert("RGBA")
    return [im.getpixel((x, y)) for x in range(16) for y in range(16)]


def baby_copper(img, model, atlas, jar, wheel):
    bv.palette_map(img, NOT_EYE, copper_palette(jar))
    eyes(img, (240, 150, 60), (255, 200, 70))
    cop = lambda f, i, j, fw, fh: (196, 104, 70) if f != "top" else (226, 136, 98)
    add_box(model, atlas, img, "head", [-0.5, 16, -0.5, 1, 2, 1], cop)
    add_box(model, atlas, img, "head", [-1, 18, -1, 2, 1, 2], cop)
    if wheel:
        for leg in ("right_leg", "left_leg"):
            part(model, leg)["boxes"] = []
        rim = lambda f, i, j, fw, fh: (120, 62, 40) if f in ("left", "right") and (i in (0, fw - 1) or j in (0, fh - 1)) else (196, 104, 70)
        add_box(model, atlas, img, "body", [-0.5, -2, -2, 1, 4, 4], rim, sub=dict(id="baby_wheel", translate=[0, 2, 0]))
        part(model, "body")["animations"] = [{"baby_wheel.rx": "limb_swing * 0.8"}]


FISH_GREEN, FISH_BLUE, KELP = (130, 200, 125), (110, 160, 205), (60, 48, 26)


def baby_fishfolk(img, model, atlas):
    bv.recolor(img, lambda x, y, p: SKINLIKE(x, y, p) and y < 23, FISH_GREEN)      # head, arms
    bv.recolor(img, lambda x, y, p: SKINLIKE(x, y, p) and y >= 23, FISH_BLUE)      # legs
    bv.recolor(img, lambda x, y, p: 15 <= y < 26 and x < 16 and p[0] < 130 and abs(p[0] - p[2]) < 25, KELP)  # tunic
    eyes(img, (24, 24, 34), (24, 24, 34))
    fill(img, (8, 11, 14, 12), (112, 180, 108))                                    # no brows
    fin = lambda f, i, j, fw, fh: ((170, 230, 200) if j == 0 else (96, 170, 140)) if f in ("front", "back") else (96, 170, 140)
    add_box(model, atlas, img, "head", [4, 10, 1, 2, 4, 0], fin)
    add_box(model, atlas, img, "head", [-6, 10, 1, 2, 4, 0], fin)
    crest = lambda f, i, j, fw, fh: ((170, 230, 200) if j == 0 else (96, 170, 140)) if f in ("left", "right") else None
    add_box(model, atlas, img, "head", [0, 16, -2, 0, 2, 5], crest)


KOBOLD = (128, 117, 64)


def baby_kobold(img, model, atlas):
    bv.recolor(img, SKINLIKE, KOBOLD)
    bv.recolor(img, lambda x, y, p: 15 <= y < 26 and x < 16 and p[0] < 130 and abs(p[0] - p[2]) < 25, (100, 115, 95))
    eyes(img, (230, 200, 60), (30, 30, 20))
    fill(img, (8, 11, 14, 12), (92, 84, 44))
    snout = lambda f, i, j, fw, fh: None if f == "back" else ((40, 36, 20) if f == "front" and j == 0 and i in (0, 2) else (118, 108, 58))
    add_box(model, atlas, img, "head", [-1.5, 8, -5.5, 3, 2, 2], snout)
    horn = lambda f, i, j, fw, fh: (226, 214, 184)
    add_box(model, atlas, img, "head", [1.5, 16, 0, 1, 2, 1], horn)
    add_box(model, atlas, img, "head", [-2.5, 16, 0, 1, 2, 1], horn)
    tail = lambda f, i, j, fw, fh: (118, 108, 58) if (i + j) % 3 else (96, 88, 46)
    add_box(model, atlas, img, "body", [-0.5, -0.5, 0, 1, 1, 4], tail, sub=dict(id="baby_tail", translate=[0, 3.5, 1.5], rotate=[35, 0, 0]))
    part(model, "body")["animations"] = [{"baby_tail.ry": "torad(18) * sin(age * 0.2)"}]


# ---- accessories (positions on the baby texture) -------------------------------------------
def acc_freckles(img):
    px = img.load()
    for p in [(8, 13), (9, 14), (13, 13), (12, 13)]:
        px[p] = tuple(max(0, c - 38) for c in px[p][:3]) + (255,)
    return img


def acc_circlet(img):
    bv.put(img, [(x, 10) for x in range(0, 30)], (205, 210, 222))
    return bv.put(img, [(10, 10), (11, 10)], (70, 140, 220))


def acc_scar(img):
    return bv.put(img, [(13, 10), (12, 11)], (196, 118, 104))


def acc_pearls(img):
    px = img.load()
    for i, x in enumerate(range(0, 14)):
        if px[x, 18][3]:
            px[x, 18] = ((242, 240, 232) if i % 2 == 0 else (206, 200, 190)) + (255,)
    return img


def acc_horn_rings(img, horn_uvs):
    for u, v in horn_uvs:
        bv.put(img, [(u + i, v + 1 + 1) for i in range(4)], (226, 178, 56))
    return img


def main():
    jar = zipfile.ZipFile(JAR)
    vanilla_png = Image.open(io.BytesIO(jar.read("assets/minecraft/textures/entity/villager/villager_baby.png"))).convert("RGBA")
    hobbit_hair = lambda x, y, p: tuple(p[:3]) in set(HOBBIT_PAL)
    dwarf_hair = lambda x, y, p: tuple(p[:3]) in set(DWARF_PAL) | {(158, 92, 46)}
    races = [  # team, number, builder, variant recipes
        ("race_hobbit", 2, baby_hobbit, lambda: bv.humanoid(2, hobbit_hair, bv.HOBBIT_HAIR, acc_freckles)),
        ("race_elf", 3, baby_elf, lambda: bv.humanoid(3, None, bv.ELF_EYES, acc_circlet)),
        ("race_copper_legs", 4, lambda i, m, a: baby_copper(i, m, a, jar, False), lambda: bv.copper(jar)),
        ("race_copper_wheel", 5, lambda i, m, a: baby_copper(i, m, a, jar, True), lambda: bv.copper(jar)),
        ("race_fishfolk", 6, baby_fishfolk, lambda: bv.scales(bv.FISH_SKIN, bv.FISH_SCHEMES, acc_pearls)),
        ("race_kobold", 7, baby_kobold, None),
        ("race_dwarf", 8, baby_dwarf, lambda: bv.humanoid(8, dwarf_hair, bv.DWARF_HAIRS, acc_scar)),
    ]
    with open(f"{CEM}/villager_baby.jem", "w", encoding="utf-8", newline="\n") as f:
        json.dump(VANILLA, f, indent="\t")
    tex_rules, model_rules = [], []
    for team, n, build, recipes in races:
        img, model, atlas = vanilla_png.copy(), copy.deepcopy(VANILLA), Atlas(vanilla_png)
        model["credit"] = f"{team} baby, generated by build_babies.py"
        build(img, model, atlas)
        if team == "race_kobold":                       # earrings go on the horns this baby just got
            horns = [b["textureOffset"] for b in part(model, "head")["boxes"][-2:]]
            recipes = lambda: bv.scales(bv.band(30, 80, 0.3), bv.KOBOLD_SCHEMES, lambda im: acc_horn_rings(im, horns))
        with open(f"{CEM}/villager_baby{n}.jem", "w", encoding="utf-8", newline="\n") as f:
            json.dump(model, f, indent="\t")
        img.save(f"{RAND}/villager_baby{n}.png")
        for old in glob.glob(f"{RAND}/villager_baby{n}[0-9][0-9].png"):   # drop variants from earlier runs
            os.remove(old)
        nums, k = [str(n)], 0
        for name, make in recipes():
            if name in ("base", "base/plain", "base/base/plain"):
                continue
            k += 1
            make(img.copy()).save(f"{RAND}/villager_baby{n}{k:02d}.png")
            nums.append(f"{n}{k:02d}")
        if team in race_teams.COPPER_LOOKS:            # weathering stage is datapack state, not random
            tex_rules += [(team + st, [num]) for st, num in zip(race_teams.COPPER_STAGES, nums)]
        else:
            tex_rules.append((team, nums))
        model_rules.append((team, n))
        print(f"{team}: baby model + {len(nums)} looks")
    with open(f"{RAND}/villager_baby.properties", "w", encoding="utf-8", newline="\n") as f:
        f.write(HDR + "".join(f"\nskins.{i}={' '.join(ns)}\nteams.{i}={t}\n" for i, (t, ns) in enumerate(tex_rules, 1)))
    with open(f"{CEM}/villager_baby.properties", "w", encoding="utf-8", newline="\n") as f:
        f.write(HDR + "".join(f"\nmodels.{i}={n}\nteams.{i}={all_stages(t)}\n" for i, (t, n) in enumerate(model_rules, 1)))
    # no biome clothing on copper, fishfolk and kobold babies
    os.makedirs(f"{RAND}/baby", exist_ok=True)
    blank = Image.new("RGBA", (64, 64), (0, 0, 0, 0))
    no_biome = [("race_copper_legs", 4), ("race_copper_wheel", 5), ("race_fishfolk", 6), ("race_kobold", 7)]
    for name in sorted(n.rsplit("/", 1)[1][:-4] for n in jar.namelist()
                       if n.startswith("assets/minecraft/textures/entity/villager/baby/") and n.endswith(".png")):
        for _, n in no_biome:
            blank.save(f"{RAND}/baby/{name}{n}.png")
        with open(f"{RAND}/baby/{name}.properties", "w", encoding="utf-8", newline="\n") as f:
            f.write(HDR + "".join(f"\nskins.{i}={n}\nteams.{i}={all_stages(t)}\n" for i, (t, n) in enumerate(no_biome, 1)))


if __name__ == "__main__":
    main()
