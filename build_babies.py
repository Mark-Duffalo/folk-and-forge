"""Baby villager models, skins and variants for every race.

26.x babies use their own model (EMF name `villager_baby`, same OptiFine part names as adults:
head, headwear, headwear2, nose, body, bodywear, arms, right_leg, left_leg) and their own 64x64
texture layout. Every race baby starts from the vanilla baby geometry, which was read from
net/minecraft/client/model/npc/BabyVillagerModel in the 26.3 jar, so vanilla baby biome overlays fit
hobbit, elf and dwarf babies as they are. Race extras (ears, beard, fins, snout, horns, tail,
lightning rod, wheel) use free texture space. Copper, fishfolk and kobold babies get transparent
biome overlays, like their adults.

Variants reuse the adult recipes from build_variants.py in the same order, so ETF's per-villager
pick should give a baby the same hair/skin/scheme it keeps as an adult (check this in game).

Usage: python build_babies.py [path/to/26.3.jar]      (re-runnable)
Writes cem/villager_baby.jem (+ .properties, villager_baby<N>.jem), random/.../villager_baby*.png,
random/.../villager_baby.properties and random/.../baby/<biome>.properties (+ blank PNGs).
"""
